//! Gates and their action on Pauli strings in the Heisenberg picture.

use crate::{Error, PauliOp, PauliString};
use std::f64::consts::FRAC_PI_4;

/// A gate, written as it acts on states (Schrödinger picture).
#[derive(Clone, Debug, PartialEq)]
pub enum Gate {
    H(usize),
    X(usize),
    Y(usize),
    Z(usize),
    S(usize),
    Sdg(usize),
    /// Square root of X.
    Sx(usize),
    Sxdg(usize),
    /// Controlled X with `(control, target)`.
    Cx(usize, usize),
    /// Controlled Y with `(control, target)`.
    Cy(usize, usize),
    Cz(usize, usize),
    Swap(usize, usize),
    /// The rotation `exp(-i * theta / 2 * P)` generated by the Pauli string `P`.
    Rotation {
        generator: Vec<(usize, PauliOp)>,
        theta: f64,
    },
}

impl Gate {
    /// The rotation `exp(-i * theta / 2 * P)`, where `P` is given as `(qubit, operator)` pairs.
    /// Identity operators are dropped.
    #[must_use]
    pub fn rotation(generator: &[(usize, PauliOp)], theta: f64) -> Self {
        Gate::Rotation {
            generator: generator
                .iter()
                .copied()
                .filter(|&(_, op)| op != PauliOp::I)
                .collect(),
            theta,
        }
    }

    #[must_use]
    pub fn rx(theta: f64, q: usize) -> Self {
        Self::rotation(&[(q, PauliOp::X)], theta)
    }

    #[must_use]
    pub fn ry(theta: f64, q: usize) -> Self {
        Self::rotation(&[(q, PauliOp::Y)], theta)
    }

    #[must_use]
    pub fn rz(theta: f64, q: usize) -> Self {
        Self::rotation(&[(q, PauliOp::Z)], theta)
    }

    #[must_use]
    pub fn rxx(theta: f64, q0: usize, q1: usize) -> Self {
        Self::rotation(&[(q0, PauliOp::X), (q1, PauliOp::X)], theta)
    }

    #[must_use]
    pub fn ryy(theta: f64, q0: usize, q1: usize) -> Self {
        Self::rotation(&[(q0, PauliOp::Y), (q1, PauliOp::Y)], theta)
    }

    #[must_use]
    pub fn rzz(theta: f64, q0: usize, q1: usize) -> Self {
        Self::rotation(&[(q0, PauliOp::Z), (q1, PauliOp::Z)], theta)
    }

    /// The T gate, which equals `rz(pi / 4)` up to a global phase.
    #[must_use]
    pub fn t(q: usize) -> Self {
        Self::rz(FRAC_PI_4, q)
    }

    #[must_use]
    pub fn tdg(q: usize) -> Self {
        Self::rz(-FRAC_PI_4, q)
    }

    /// The Toffoli gate as Clifford and T gates, in the order they act on a state.
    #[must_use]
    pub fn ccx(c0: usize, c1: usize, t: usize) -> [Gate; 15] {
        [
            Gate::H(t),
            Gate::Cx(c1, t),
            Gate::tdg(t),
            Gate::Cx(c0, t),
            Gate::t(t),
            Gate::Cx(c1, t),
            Gate::tdg(t),
            Gate::Cx(c0, t),
            Gate::t(c1),
            Gate::t(t),
            Gate::H(t),
            Gate::Cx(c0, c1),
            Gate::t(c0),
            Gate::tdg(c1),
            Gate::Cx(c0, c1),
        ]
    }

    /// Checks that the gate acts on distinct qubits below `num_qubits`.
    pub fn validate(&self, num_qubits: usize) -> Result<(), Error> {
        let check = |q: usize| {
            if q < num_qubits {
                Ok(())
            } else {
                Err(Error::QubitOutOfRange {
                    qubit: q,
                    num_qubits,
                })
            }
        };
        match self {
            Gate::H(q)
            | Gate::X(q)
            | Gate::Y(q)
            | Gate::Z(q)
            | Gate::S(q)
            | Gate::Sdg(q)
            | Gate::Sx(q)
            | Gate::Sxdg(q) => check(*q),
            Gate::Cx(a, b) | Gate::Cy(a, b) | Gate::Cz(a, b) | Gate::Swap(a, b) => {
                check(*a)?;
                check(*b)?;
                if a == b {
                    return Err(Error::DuplicateQubit { qubit: *a });
                }
                Ok(())
            }
            Gate::Rotation { generator, theta } => {
                if !theta.is_finite() {
                    return Err(Error::NonFiniteAngle);
                }
                for (i, &(q, _)) in generator.iter().enumerate() {
                    check(q)?;
                    if generator[..i].iter().any(|&(other, _)| other == q) {
                        return Err(Error::DuplicateQubit { qubit: q });
                    }
                }
                Ok(())
            }
        }
    }

    /// Replaces `p` by `± U† p U` for a Clifford gate `U` and returns whether the sign is minus.
    ///
    /// # Panics
    /// If the gate is a rotation, which maps one Pauli string to two.
    #[inline]
    pub(crate) fn conjugate_clifford<const W: usize>(&self, p: &mut PauliString<W>) -> bool {
        match *self {
            Gate::H(q) => {
                let (x, z) = (p.x_bit(q), p.z_bit(q));
                if x != z {
                    p.flip_x(q);
                    p.flip_z(q);
                }
                x && z
            }
            Gate::X(q) => p.z_bit(q),
            Gate::Y(q) => p.x_bit(q) != p.z_bit(q),
            Gate::Z(q) => p.x_bit(q),
            // S† X S = -Y, S† Y S = X
            Gate::S(q) => {
                let (x, z) = (p.x_bit(q), p.z_bit(q));
                if x {
                    p.flip_z(q);
                }
                x && !z
            }
            // S X S† = Y, S Y S† = -X
            Gate::Sdg(q) => {
                let (x, z) = (p.x_bit(q), p.z_bit(q));
                if x {
                    p.flip_z(q);
                }
                x && z
            }
            // SX† Z SX = Y, SX† Y SX = -Z
            Gate::Sx(q) => {
                let (x, z) = (p.x_bit(q), p.z_bit(q));
                if z {
                    p.flip_x(q);
                }
                x && z
            }
            // SX Z SX† = -Y, SX Y SX† = Z
            Gate::Sxdg(q) => {
                let (x, z) = (p.x_bit(q), p.z_bit(q));
                if z {
                    p.flip_x(q);
                }
                z && !x
            }
            Gate::Cx(c, t) => {
                let (xc, zc, xt, zt) = (p.x_bit(c), p.z_bit(c), p.x_bit(t), p.z_bit(t));
                if xc {
                    p.flip_x(t);
                }
                if zt {
                    p.flip_z(c);
                }
                xc && zt && (xt == zc)
            }
            // CY = S(t) CX S†(t)
            Gate::Cy(c, t) => {
                let a = Gate::S(t).conjugate_clifford(p);
                let b = Gate::Cx(c, t).conjugate_clifford(p);
                let d = Gate::Sdg(t).conjugate_clifford(p);
                a ^ b ^ d
            }
            Gate::Cz(a, b) => {
                let (xa, za, xb, zb) = (p.x_bit(a), p.z_bit(a), p.x_bit(b), p.z_bit(b));
                if xb {
                    p.flip_z(a);
                }
                if xa {
                    p.flip_z(b);
                }
                xa && xb && (za != zb)
            }
            Gate::Swap(a, b) => {
                let (pa, pb) = (p.get(a), p.get(b));
                p.set(a, pb);
                p.set(b, pa);
                false
            }
            Gate::Rotation { .. } => unreachable!("a rotation is not a Clifford gate"),
        }
    }
}
