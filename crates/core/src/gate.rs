//! Gates and noise channels, and their action on Pauli strings in the Heisenberg picture.

use crate::{Error, PauliOp, PauliString};
use num_complex::Complex64;
use std::f64::consts::FRAC_PI_4;

/// The most qubits a Pauli channel can act on; its table has `4^n` entries.
const MAX_CHANNEL_QUBITS: usize = 6;

/// The most qubits a transfer map can act on; its matrix has `16^n` entries.
const MAX_MAP_QUBITS: usize = 5;

/// Entries of a transfer matrix smaller than this are taken to be zero, as in PauliPropagation.jl.
const MAP_TOLERANCE: f64 = 1e-15;

/// How far `U† U` of a unitary gate may be from the identity, entry by entry.
const UNITARY_TOLERANCE: f64 = 1e-10;

/// A gate or noise channel, written as it acts on states (Schrödinger picture).
#[derive(Clone, Debug, PartialEq)]
pub enum Gate {
    H(usize),
    X(usize),
    Y(usize),
    Z(usize),
    S(usize),
    Sdg(usize),
    /// Square root of X.
    Sx(usize),
    Sxdg(usize),
    /// Controlled X with `(control, target)`.
    Cx(usize, usize),
    /// Controlled Y with `(control, target)`.
    Cy(usize, usize),
    Cz(usize, usize),
    Swap(usize, usize),
    /// The rotation `exp(-i * theta / 2 * P)` generated by the Pauli string `P`.
    Rotation {
        generator: Vec<(usize, PauliOp)>,
        theta: f64,
    },
    /// A channel that is diagonal in the Pauli basis, such as a random Pauli error.
    ///
    /// A Pauli string is multiplied by `factors[index]`, where `index` is the number whose
    /// `i`-th base-4 digit is the operator on `qubits[i]`, with `I, X, Y, Z = 0, 1, 2, 3`.
    PauliChannel {
        qubits: Vec<usize>,
        factors: Vec<f64>,
    },
    /// Amplitude damping, which takes the state 1 to the state 0 with probability `gamma`.
    AmplitudeDamping {
        qubit: usize,
        gamma: f64,
    },
    /// A linear map of the Pauli strings on `qubits`, given by its action on an observable.
    ///
    /// The Pauli string with index `j` on the qubits becomes the sum of `factor * P_i` over
    /// the `(i, factor)` in `columns[j]`. The index of a string is the number whose `i`-th
    /// base-4 digit is the operator on `qubits[i]`, with `I, X, Y, Z = 0, 1, 2, 3`.
    TransferMap {
        qubits: Vec<usize>,
        columns: Vec<Vec<(usize, f64)>>,
    },
}

fn digit(op: PauliOp) -> usize {
    match op {
        PauliOp::I => 0,
        PauliOp::X => 1,
        PauliOp::Y => 2,
        PauliOp::Z => 3,
    }
}

fn check_strength(value: f64, what: &'static str) -> Result<(), Error> {
    if (0.0..=1.0).contains(&value) {
        Ok(())
    } else {
        Err(Error::InvalidNoise(what))
    }
}

impl Gate {
    /// The rotation `exp(-i * theta / 2 * P)`, where `P` is given as `(qubit, operator)` pairs.
    /// Identity operators are dropped.
    #[must_use]
    pub fn rotation(generator: &[(usize, PauliOp)], theta: f64) -> Self {
        Gate::Rotation {
            generator: generator
                .iter()
                .copied()
                .filter(|&(_, op)| op != PauliOp::I)
                .collect(),
            theta,
        }
    }

    #[must_use]
    pub fn rx(theta: f64, q: usize) -> Self {
        Self::rotation(&[(q, PauliOp::X)], theta)
    }

    #[must_use]
    pub fn ry(theta: f64, q: usize) -> Self {
        Self::rotation(&[(q, PauliOp::Y)], theta)
    }

    #[must_use]
    pub fn rz(theta: f64, q: usize) -> Self {
        Self::rotation(&[(q, PauliOp::Z)], theta)
    }

    #[must_use]
    pub fn rxx(theta: f64, q0: usize, q1: usize) -> Self {
        Self::rotation(&[(q0, PauliOp::X), (q1, PauliOp::X)], theta)
    }

    #[must_use]
    pub fn ryy(theta: f64, q0: usize, q1: usize) -> Self {
        Self::rotation(&[(q0, PauliOp::Y), (q1, PauliOp::Y)], theta)
    }

    #[must_use]
    pub fn rzz(theta: f64, q0: usize, q1: usize) -> Self {
        Self::rotation(&[(q0, PauliOp::Z), (q1, PauliOp::Z)], theta)
    }

    /// The T gate, which equals `rz(pi / 4)` up to a global phase.
    #[must_use]
    pub fn t(q: usize) -> Self {
        Self::rz(FRAC_PI_4, q)
    }

    #[must_use]
    pub fn tdg(q: usize) -> Self {
        Self::rz(-FRAC_PI_4, q)
    }

    /// The channel that applies the Pauli string `errors[k].0` with probability `errors[k].1`
    /// and nothing otherwise. Operator `i` of an error string acts on `qubits[i]`.
    ///
    /// In the Heisenberg picture a Pauli string `P` keeps the factor `1 - 2 p`, where `p` is
    /// the total probability of the errors that anticommute with `P`.
    pub fn pauli_channel(qubits: &[usize], errors: &[(Vec<PauliOp>, f64)]) -> Result<Self, Error> {
        let n = qubits.len();
        if n == 0 || n > MAX_CHANNEL_QUBITS {
            return Err(Error::InvalidNoise(
                "a Pauli channel acts on between one and six qubits",
            ));
        }
        let mut total = 0.0;
        for (ops, probability) in errors {
            if ops.len() != n {
                return Err(Error::InvalidNoise(
                    "an error string has to give one operator per qubit of the channel",
                ));
            }
            check_strength(*probability, "an error probability is not between 0 and 1")?;
            total += probability;
        }
        if total > 1.0 + 1e-9 {
            return Err(Error::InvalidNoise(
                "the error probabilities sum to more than 1",
            ));
        }

        let factors = (0..1usize << (2 * n))
            .map(|index| {
                let anticommuting: f64 = errors
                    .iter()
                    .filter(|(ops, _)| {
                        // Two strings anticommute if they differ, both without an identity,
                        // on an odd number of qubits.
                        let clashes = ops
                            .iter()
                            .enumerate()
                            .filter(|&(i, &op)| {
                                let other = (index >> (2 * i)) & 3;
                                op != PauliOp::I && other != 0 && other != digit(op)
                            })
                            .count();
                        clashes % 2 == 1
                    })
                    .map(|&(_, probability)| probability)
                    .sum();
                1.0 - 2.0 * anticommuting
            })
            .collect();
        Ok(Gate::PauliChannel {
            qubits: qubits.to_vec(),
            factors,
        })
    }

    /// Depolarizing noise, which multiplies X, Y and Z on the qubit by `1 - strength`.
    ///
    /// This is a random X, Y or Z error with probability `strength / 4` each.
    pub fn depolarizing(strength: f64, q: usize) -> Result<Self, Error> {
        Self::pauli_damping(strength, q, [true, true, true])
    }

    /// Pauli X noise, which multiplies Y and Z on the qubit by `1 - strength`.
    ///
    /// This is a random X error with probability `strength / 2`.
    pub fn pauli_x_noise(strength: f64, q: usize) -> Result<Self, Error> {
        Self::pauli_damping(strength, q, [false, true, true])
    }

    /// Pauli Y noise, which multiplies X and Z on the qubit by `1 - strength`.
    ///
    /// This is a random Y error with probability `strength / 2`.
    pub fn pauli_y_noise(strength: f64, q: usize) -> Result<Self, Error> {
        Self::pauli_damping(strength, q, [true, false, true])
    }

    /// Pauli Z noise, or dephasing, which multiplies X and Y on the qubit by `1 - strength`.
    ///
    /// This is a random Z error with probability `strength / 2`.
    pub fn pauli_z_noise(strength: f64, q: usize) -> Result<Self, Error> {
        Self::pauli_damping(strength, q, [true, true, false])
    }

    fn pauli_damping(strength: f64, q: usize, damped: [bool; 3]) -> Result<Self, Error> {
        check_strength(strength, "a noise strength is not between 0 and 1")?;
        let factor = |is_damped: bool| if is_damped { 1.0 - strength } else { 1.0 };
        Ok(Gate::PauliChannel {
            qubits: vec![q],
            factors: vec![1.0, factor(damped[0]), factor(damped[1]), factor(damped[2])],
        })
    }

    /// Amplitude damping with decay probability `gamma`.
    ///
    /// In the Heisenberg picture X and Y on the qubit are multiplied by `sqrt(1 - gamma)`,
    /// and Z becomes `(1 - gamma) Z + gamma I`.
    pub fn amplitude_damping(gamma: f64, q: usize) -> Result<Self, Error> {
        check_strength(gamma, "a damping probability is not between 0 and 1")?;
        Ok(Gate::AmplitudeDamping { qubit: q, gamma })
    }

    /// The gate with the transfer matrix `matrix` in the Pauli basis, as it acts on an observable.
    ///
    /// `matrix` holds `4^n` rows of `4^n` entries for `n` qubits. The Pauli string with index
    /// `j` on the qubits becomes the sum over `i` of `matrix[i * 4^n + j] * P_i`, where the
    /// `i`-th base-4 digit of an index is the operator on `qubits[i]`, with
    /// `I, X, Y, Z = 0, 1, 2, 3`.
    pub fn transfer_map(qubits: &[usize], matrix: &[f64]) -> Result<Self, Error> {
        let n = qubits.len();
        if n == 0 || n > MAX_MAP_QUBITS {
            return Err(Error::InvalidMatrix(
                "a transfer map acts on between one and five qubits",
            ));
        }
        let dim = 1usize << (2 * n);
        if matrix.len() != dim * dim {
            return Err(Error::InvalidMatrix(
                "a transfer matrix on n qubits has 4^n rows and 4^n columns",
            ));
        }
        if matrix.iter().any(|value| !value.is_finite()) {
            return Err(Error::InvalidMatrix(
                "an entry of the transfer matrix is not finite",
            ));
        }
        let columns = (0..dim)
            .map(|j| {
                (0..dim)
                    .map(|i| (i, matrix[i * dim + j]))
                    .filter(|&(_, value)| value != 0.0)
                    .collect()
            })
            .collect();
        Ok(Gate::TransferMap {
            qubits: qubits.to_vec(),
            columns,
        })
    }

    /// The gate with the unitary `matrix`, as it acts on a state.
    ///
    /// `matrix` holds `2^n` rows of `2^n` entries for `n` qubits, and `qubits[0]` is the most
    /// significant bit of a row or column index, so that the matrix of independent gates on
    /// the qubits is their Kronecker product in the order of `qubits`.
    pub fn unitary(qubits: &[usize], matrix: &[Complex64]) -> Result<Self, Error> {
        let n = qubits.len();
        if n == 0 || n > MAX_MAP_QUBITS {
            return Err(Error::InvalidMatrix(
                "a unitary gate acts on between one and five qubits",
            ));
        }
        let dim = 1usize << n;
        if matrix.len() != dim * dim {
            return Err(Error::InvalidMatrix(
                "a unitary matrix on n qubits has 2^n rows and 2^n columns",
            ));
        }
        for a in 0..dim {
            for b in 0..dim {
                let entry: Complex64 = (0..dim)
                    .map(|r| matrix[r * dim + a].conj() * matrix[r * dim + b])
                    .sum();
                let expected = if a == b { 1.0 } else { 0.0 };
                let distance = (entry - expected).norm();
                if distance.is_nan() || distance > UNITARY_TOLERANCE {
                    return Err(Error::InvalidMatrix("the matrix is not unitary"));
                }
            }
        }

        // The Pauli string with index `j`, as the bits it flips, the bits it reads for a
        // sign, and its number of Y operators. Qubit `i` is bit `n - 1 - i` of a basis state.
        let masks = |index: usize| {
            let (mut x, mut z, mut ys) = (0usize, 0usize, 0u32);
            for i in 0..n {
                let bit = 1 << (n - 1 - i);
                match (index >> (2 * i)) & 3 {
                    1 => x |= bit,
                    2 => {
                        x |= bit;
                        z |= bit;
                        ys += 1;
                    }
                    3 => z |= bit,
                    _ => {}
                }
            }
            (x, z, ys)
        };
        // The entry of the Pauli string in the column `column`, which is in the row `column ^ x`.
        let entry = |z: usize, ys: u32, column: usize| {
            let sign = if (column & z).count_ones() & 1 == 0 {
                1.0
            } else {
                -1.0
            };
            Complex64::i().powu(ys) * sign
        };

        let strings = 1usize << (2 * n);
        let mut columns = vec![Vec::new(); strings];
        let mut conjugated = vec![Complex64::new(0.0, 0.0); dim * dim];
        for (j, column) in columns.iter_mut().enumerate() {
            // conjugated = U† P_j U
            let (xj, zj, ysj) = masks(j);
            for a in 0..dim {
                for c in 0..dim {
                    conjugated[a * dim + c] = (0..dim)
                        .map(|r| {
                            matrix[r * dim + a].conj()
                                * entry(zj, ysj, r ^ xj)
                                * matrix[(r ^ xj) * dim + c]
                        })
                        .sum();
                }
            }
            // The factor of P_i is Tr[P_i U† P_j U] / 2^n.
            for i in 0..strings {
                let (xi, zi, ysi) = masks(i);
                let trace: Complex64 = (0..dim)
                    .map(|r| entry(zi, ysi, r ^ xi) * conjugated[(r ^ xi) * dim + r])
                    .sum();
                let factor = trace.re / dim as f64;
                if factor.abs() >= MAP_TOLERANCE {
                    column.push((i, factor));
                }
            }
        }
        Ok(Gate::TransferMap {
            qubits: qubits.to_vec(),
            columns,
        })
    }

    /// The gate that acts on an observable the way this gate acts on a state: the inverse of
    /// a unitary gate, and the adjoint map of a channel.
    #[must_use]
    pub fn adjoint(&self) -> Gate {
        match self {
            Gate::S(q) => Gate::Sdg(*q),
            Gate::Sdg(q) => Gate::S(*q),
            Gate::Sx(q) => Gate::Sxdg(*q),
            Gate::Sxdg(q) => Gate::Sx(*q),
            Gate::Rotation { generator, theta } => Gate::Rotation {
                generator: generator.clone(),
                theta: -theta,
            },
            // On an observable Z becomes (1 - gamma) Z + gamma I, so on a state the identity
            // becomes I + gamma Z and Z becomes (1 - gamma) Z.
            Gate::AmplitudeDamping { qubit, gamma } => {
                let transverse = (1.0 - gamma).sqrt();
                Gate::TransferMap {
                    qubits: vec![*qubit],
                    columns: vec![
                        vec![(0, 1.0), (3, *gamma)],
                        vec![(1, transverse)],
                        vec![(2, transverse)],
                        vec![(3, 1.0 - gamma)],
                    ],
                }
            }
            Gate::TransferMap { qubits, columns } => {
                let mut transposed = vec![Vec::new(); columns.len()];
                for (j, column) in columns.iter().enumerate() {
                    for &(i, factor) in column {
                        transposed[i].push((j, factor));
                    }
                }
                Gate::TransferMap {
                    qubits: qubits.clone(),
                    columns: transposed,
                }
            }
            // The other Clifford gates are their own inverses, and a channel that is diagonal
            // in the Pauli basis is its own adjoint.
            Gate::H(_)
            | Gate::X(_)
            | Gate::Y(_)
            | Gate::Z(_)
            | Gate::Cx(..)
            | Gate::Cy(..)
            | Gate::Cz(..)
            | Gate::Swap(..)
            | Gate::PauliChannel { .. } => self.clone(),
        }
    }

    /// Whether the gate is one of the noise channels rather than a unitary. A transfer map
    /// counts as neither.
    #[must_use]
    pub fn is_noise(&self) -> bool {
        matches!(
            self,
            Gate::PauliChannel { .. } | Gate::AmplitudeDamping { .. }
        )
    }

    /// The Toffoli gate as Clifford and T gates, in the order they act on a state.
    #[must_use]
    pub fn ccx(c0: usize, c1: usize, t: usize) -> [Gate; 15] {
        [
            Gate::H(t),
            Gate::Cx(c1, t),
            Gate::tdg(t),
            Gate::Cx(c0, t),
            Gate::t(t),
            Gate::Cx(c1, t),
            Gate::tdg(t),
            Gate::Cx(c0, t),
            Gate::t(c1),
            Gate::t(t),
            Gate::H(t),
            Gate::Cx(c0, c1),
            Gate::t(c0),
            Gate::tdg(c1),
            Gate::Cx(c0, c1),
        ]
    }

    /// Checks that the gate acts on distinct qubits below `num_qubits`.
    pub fn validate(&self, num_qubits: usize) -> Result<(), Error> {
        let check = |q: usize| {
            if q < num_qubits {
                Ok(())
            } else {
                Err(Error::QubitOutOfRange {
                    qubit: q,
                    num_qubits,
                })
            }
        };
        match self {
            Gate::H(q)
            | Gate::X(q)
            | Gate::Y(q)
            | Gate::Z(q)
            | Gate::S(q)
            | Gate::Sdg(q)
            | Gate::Sx(q)
            | Gate::Sxdg(q) => check(*q),
            Gate::Cx(a, b) | Gate::Cy(a, b) | Gate::Cz(a, b) | Gate::Swap(a, b) => {
                check(*a)?;
                check(*b)?;
                if a == b {
                    return Err(Error::DuplicateQubit { qubit: *a });
                }
                Ok(())
            }
            Gate::Rotation { generator, theta } => {
                if !theta.is_finite() {
                    return Err(Error::NonFiniteAngle);
                }
                for (i, &(q, _)) in generator.iter().enumerate() {
                    check(q)?;
                    if generator[..i].iter().any(|&(other, _)| other == q) {
                        return Err(Error::DuplicateQubit { qubit: q });
                    }
                }
                Ok(())
            }
            Gate::PauliChannel { qubits, factors } => {
                for (i, &q) in qubits.iter().enumerate() {
                    check(q)?;
                    if qubits[..i].contains(&q) {
                        return Err(Error::DuplicateQubit { qubit: q });
                    }
                }
                if qubits.is_empty()
                    || qubits.len() > MAX_CHANNEL_QUBITS
                    || factors.len() != 1 << (2 * qubits.len())
                {
                    return Err(Error::InvalidNoise(
                        "a Pauli channel needs one factor per Pauli string on its qubits",
                    ));
                }
                if factors.iter().any(|f| !(-1.0..=1.0).contains(f)) {
                    return Err(Error::InvalidNoise(
                        "a factor of a Pauli channel is not between -1 and 1",
                    ));
                }
                Ok(())
            }
            Gate::AmplitudeDamping { qubit, gamma } => {
                check(*qubit)?;
                check_strength(*gamma, "a damping probability is not between 0 and 1")
            }
            Gate::TransferMap { qubits, columns } => {
                for (i, &q) in qubits.iter().enumerate() {
                    check(q)?;
                    if qubits[..i].contains(&q) {
                        return Err(Error::DuplicateQubit { qubit: q });
                    }
                }
                let strings = 1usize << (2 * qubits.len().min(MAX_MAP_QUBITS));
                if qubits.is_empty() || qubits.len() > MAX_MAP_QUBITS || columns.len() != strings {
                    return Err(Error::InvalidMatrix(
                        "a transfer map needs one column per Pauli string on its qubits",
                    ));
                }
                if columns
                    .iter()
                    .flatten()
                    .any(|&(i, factor)| i >= strings || !factor.is_finite())
                {
                    return Err(Error::InvalidMatrix(
                        "an entry of a transfer map is out of range or not finite",
                    ));
                }
                Ok(())
            }
        }
    }

    /// Replaces the operators of `p` on `qubits` by those of the Pauli string with `index`.
    #[inline]
    pub(crate) fn with_index<const W: usize>(
        qubits: &[usize],
        mut p: PauliString<W>,
        index: usize,
    ) -> PauliString<W> {
        const OPS: [PauliOp; 4] = [PauliOp::I, PauliOp::X, PauliOp::Y, PauliOp::Z];
        for (i, &q) in qubits.iter().enumerate() {
            p.set(q, OPS[(index >> (2 * i)) & 3]);
        }
        p
    }

    /// The index of the operators of `p` on `qubits`, as a Pauli channel and a transfer map
    /// number the Pauli strings on their qubits.
    #[inline]
    pub(crate) fn channel_index<const W: usize>(qubits: &[usize], p: &PauliString<W>) -> usize {
        qubits
            .iter()
            .enumerate()
            .fold(0, |index, (i, &q)| index | (digit(p.get(q)) << (2 * i)))
    }

    /// Replaces `p` by `± U† p U` for a Clifford gate `U` and returns whether the sign is minus.
    ///
    /// # Panics
    /// If the gate is not a Clifford gate.
    #[inline]
    pub(crate) fn conjugate_clifford<const W: usize>(&self, p: &mut PauliString<W>) -> bool {
        match *self {
            Gate::H(q) => {
                let (x, z) = (p.x_bit(q), p.z_bit(q));
                if x != z {
                    p.flip_x(q);
                    p.flip_z(q);
                }
                x && z
            }
            Gate::X(q) => p.z_bit(q),
            Gate::Y(q) => p.x_bit(q) != p.z_bit(q),
            Gate::Z(q) => p.x_bit(q),
            // S† X S = -Y, S† Y S = X
            Gate::S(q) => {
                let (x, z) = (p.x_bit(q), p.z_bit(q));
                if x {
                    p.flip_z(q);
                }
                x && !z
            }
            // S X S† = Y, S Y S† = -X
            Gate::Sdg(q) => {
                let (x, z) = (p.x_bit(q), p.z_bit(q));
                if x {
                    p.flip_z(q);
                }
                x && z
            }
            // SX† Z SX = Y, SX† Y SX = -Z
            Gate::Sx(q) => {
                let (x, z) = (p.x_bit(q), p.z_bit(q));
                if z {
                    p.flip_x(q);
                }
                x && z
            }
            // SX Z SX† = -Y, SX Y SX† = Z
            Gate::Sxdg(q) => {
                let (x, z) = (p.x_bit(q), p.z_bit(q));
                if z {
                    p.flip_x(q);
                }
                z && !x
            }
            Gate::Cx(c, t) => {
                let (xc, zc, xt, zt) = (p.x_bit(c), p.z_bit(c), p.x_bit(t), p.z_bit(t));
                if xc {
                    p.flip_x(t);
                }
                if zt {
                    p.flip_z(c);
                }
                xc && zt && (xt == zc)
            }
            // CY = S(t) CX S†(t)
            Gate::Cy(c, t) => {
                let a = Gate::S(t).conjugate_clifford(p);
                let b = Gate::Cx(c, t).conjugate_clifford(p);
                let d = Gate::Sdg(t).conjugate_clifford(p);
                a ^ b ^ d
            }
            Gate::Cz(a, b) => {
                let (xa, za, xb, zb) = (p.x_bit(a), p.z_bit(a), p.x_bit(b), p.z_bit(b));
                if xb {
                    p.flip_z(a);
                }
                if xa {
                    p.flip_z(b);
                }
                xa && xb && (za != zb)
            }
            Gate::Swap(a, b) => {
                let (pa, pb) = (p.get(a), p.get(b));
                p.set(a, pb);
                p.set(b, pa);
                false
            }
            Gate::Rotation { .. }
            | Gate::PauliChannel { .. }
            | Gate::AmplitudeDamping { .. }
            | Gate::TransferMap { .. } => {
                unreachable!("not a Clifford gate")
            }
        }
    }
}
